<script>
(function(){
  let opened = false, done = false;
  let data = { requirement:'', name:'', email:'' };
  let step = 0;

  window.tpDismissTeaser = function(e) {
    e.stopPropagation();
    document.getElementById('tp-teaser').style.display = 'none';
    const solo = document.getElementById('tp-bubble-solo');
    solo.style.display = 'flex';
  };

  window.tpOpen = function() {
    document.getElementById('tp-teaser').style.display = 'none';
    document.getElementById('tp-bubble-solo').style.display = 'none';
    document.getElementById('tp-chat-window').classList.add('open');
    if (!opened) { opened = true; setTimeout(() => tpBot("Hello! 👋 Welcome to <b>Takkar Polychem</b>!<br><br>What product or requirement are you looking for?<br><small style='color:#888'>(e.g. LSZH compound, PVC compound, Masterbatch…)</small>"), 350); }
    setTimeout(() => document.getElementById('tp-input').focus(), 150);
  };

  window.tpClose = function() {
    document.getElementById('tp-chat-window').classList.remove('open');
    const solo = document.getElementById('tp-bubble-solo');
    solo.style.display = 'flex';
  };

  window.tpKey = function(e) { if(e.key==='Enter'&&!e.shiftKey){e.preventDefault();tpSend();} };
  window.tpResize = function(el) { el.style.height='auto'; el.style.height=Math.min(el.scrollHeight,80)+'px'; };

  window.tpSend = function() {
    if(done) return;
    const inp = document.getElementById('tp-input');
    const txt = inp.value.trim();
    if(!txt) return;
    inp.value=''; inp.style.height='auto';
    tpUser(txt);

    if(step===0){ data.requirement=txt; step=1; tpDelayBot("Got it! 👍<br><br>Could you please share your <b>name</b> and <b>company name</b>?"); }
    else if(step===1){ data.name=txt; step=2; tpDelayBot("Thank you! 😊<br><br>Please share your <b>email address</b> so our team can send you the details."); }
    else if(step===2){
      if(!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(txt)){ tpDelayBot("That doesn't look right. Please enter a valid email address<br>(e.g. <b>name@company.com</b>)."); return; }
      data.email=txt; step=3; done=true;
      sendThankYouEmail(data.email, data.name.split(' ')[0], data.requirement);

      document.getElementById('tp-input').disabled=true;
      document.getElementById('tp-send').disabled=true;
      document.getElementById('tp-input').placeholder='Conversation complete';
      const firstName = data.name.split(' ')[0];
      tpDelayBot("Thank you, <b>"+esc(firstName)+"</b>! ✅<br><br>We have received your enquiry for <b>"+esc(data.requirement)+"</b>.<br><br>📧 We will send you all the details on <b>"+esc(data.email)+"</b> shortly.", true);
    }
  };

  function tpBot(html) {
    const msgs = document.getElementById('tp-messages');
    const w = document.createElement('div');
    w.className='tp-msg bot';
    w.innerHTML=`<div class="tp-av">TP</div><div class="tp-bubble">${html}</div>`;
    msgs.appendChild(w); msgs.scrollTop=msgs.scrollHeight;
  }
  function tpUser(txt) {
    const msgs = document.getElementById('tp-messages');
    const w = document.createElement('div');
    w.className='tp-msg user';
    w.innerHTML=`<div class="tp-bubble">${esc(txt)}</div>`;
    msgs.appendChild(w); msgs.scrollTop=msgs.scrollHeight;
  }
  function tpDelayBot(html, isLast) {
    const msgs = document.getElementById('tp-messages');
    const t = document.createElement('div');
    t.className='tp-msg bot'; t.id='tp-typing';
    t.innerHTML=`<div class="tp-av">TP</div><div class="tp-bubble tp-typing"><span></span><span></span><span></span></div>`;
    msgs.appendChild(t); msgs.scrollTop=msgs.scrollHeight;
    setTimeout(()=>{
      const el=document.getElementById('tp-typing'); if(el) el.remove();
      tpBot(html);
      if(isLast){ setTimeout(tpShowDone,300); tpSubmit(); }
    }, 900);
  }
  function tpShowDone() {
    const msgs=document.getElementById('tp-messages');
    const b=document.createElement('div');
    b.className='tp-done-box';
    b.innerHTML='<strong>&#10003; Enquiry Submitted!</strong>Watch your inbox — we\'ll be in touch soon.';
    msgs.appendChild(b); msgs.scrollTop=msgs.scrollHeight;
  }
  function tpSubmit() {
    document.getElementById('tp-fname').value=data.name;
    document.getElementById('tp-femail').value=data.email;
    document.getElementById('tp-freq').value=data.requirement;
    document.getElementById('tp-form').submit();
  }

  function sendThankYouEmail(toEmail, toName, requirement) {
  emailjs.send("service_rs0mqn8", "template_jloo7rx", {
    to_email: toEmail,
    to_name: toName,
    requirement: requirement
  }).then(function() {
    console.log("Thank you email sent!");
  }).catch(function(error) {
    console.error("Email failed:", error);
  });
}
  function esc(s){ return s.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;'); }
})();
